// Builds cms-email/public/admin/ from public/admin/, so both CMS versions share the same
// collections and the same pinned Sveltia version. Only the backend and the site URL change.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const WORKER = 'https://federg-cms-email.enric-albert-federg.workers.dev';
// Test setup: drafts and publications go to this branch, not to main, so the published site
// does not change. Its Cloudflare preview is the "site" for this version of the editor.
const BRANCH = 'sin-github';
const SITE = 'https://sin-github.federg-conjunta.pages.dev';

const source = readFileSync('public/admin/config.yml', 'utf8');

const backend = `backend:
  name: github
  repo: rivellesep/federg-conjunta
  branch: ${BRANCH}
  # Everything goes through the Worker: Cloudflare Access checks the editor's email and the Worker
  # talks to GitHub with a GitHub App token that never reaches the browser
  base_url: ${WORKER}
  api_root: ${WORKER}/api/github
  graphql_api_root: ${WORKER}/api/github/graphql
  squash_merges: true
  auth_methods: [oauth]
  commit_messages:
    create: 'Create {{collection}} "{{slug}}"'
    update: 'Update {{collection}} "{{slug}}"'
    delete: 'Delete {{collection}} "{{slug}}"'
    uploadMedia: 'Upload "{{path}}"'
    deleteMedia: 'Delete "{{path}}"'
`;

// The backend block runs from "backend:" to the next top-level key
const withBackend = source.replace(/^backend:\n(?:[ #].*\n|\n)*?(?=^\S)/m, `${backend}\n`);
if (withBackend === source) throw new Error('backend block not found in public/admin/config.yml');

const config = withBackend
  .replace(/^site_url: .*$/m, `site_url: ${SITE}`)
  .replace(/^app_title: .*$/m, 'app_title: FEDERG CMS sin GitHub (prueba)')
  .replace(
    /^# Sveltia CMS configuration.*$/m,
    '# GENERATED by cms-email/build-config.mjs from public/admin/config.yml. Do not edit by hand.\n$&'
  );

mkdirSync('cms-email/public/admin', { recursive: true });
writeFileSync('cms-email/public/admin/config.yml', config);
writeFileSync('cms-email/public/admin/index.html', readFileSync('public/admin/index.html', 'utf8'));
writeFileSync('cms-email/public/favicon.svg', readFileSync('public/favicon.svg'));
console.log('cms-email/public/admin/ ready (branch %s)', BRANCH);
